import puppeteer from 'puppeteer'
const out = process.argv[2], w = Number(process.argv[3])
const b = await puppeteer.launch({ headless: 'new', args: ['--no-sandbox'] })
const p = await b.newPage()
await p.setViewport({ width: w, height: 820, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
await p.goto('http://localhost:3001/contact#contact-form', { waitUntil: 'networkidle0', timeout: 60000 })
await new Promise(r => setTimeout(r, 1800))
await p.evaluate(() => { const f = document.querySelector('form'); f.scrollIntoView({block:'start'}); window.scrollBy(0,-100) })
await new Promise(r => setTimeout(r, 1600))
await p.screenshot({ path: `${out}/form-${w}a.png` })
await p.evaluate(() => window.scrollBy(0, 700))
await new Promise(r => setTimeout(r, 900))
await p.screenshot({ path: `${out}/form-${w}b.png` })
await b.close()
console.log('ok')
